"""Build exp02_colab.ipynb from the .py sources (single source of truth).

  uv run python make_notebook.py
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCES = ["data.py", "train.py", "score.py", "analyze.py", "split_ids.json"]


def md(text):
    return {"cell_type": "markdown", "metadata": {}, "source": text.strip().splitlines(True)}


def code(text):
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
            "source": text.strip().splitlines(True)}


cells = [
    md("""
# exp02: small cross-encoder selector (HotpotQA distractor)

Runtime → Change runtime type → **T4 GPU**. Then *Run all*.

**Results are saved to Google Drive** (`MyDrive/qualiusp2026/exp02_results`) while training runs, so a
disconnect loses at most one checkpoint interval; just re-run all cells and training resumes.
The last cell also downloads a zip of the small result files. Put it in
`experiments/exp02_cross_encoder/results/` in the repo.

Generated by `make_notebook.py`; edit the .py files in the repo, not this notebook.
"""),
    code("""
from google.colab import drive
drive.mount('/content/drive')
import os, pathlib
os.environ['RESULTS_DIR'] = '/content/drive/MyDrive/qualiusp2026/exp02_results'
pathlib.Path(os.environ['RESULTS_DIR']).mkdir(parents=True, exist_ok=True)
pathlib.Path('/content/exp02').mkdir(exist_ok=True)
os.chdir('/content/exp02')
!nvidia-smi --query-gpu=name,memory.total --format=csv
!pip -q install tiktoken
"""),
    md("## Source files (written from the repo)"),
]
for name in SOURCES:
    cells.append(code(f"%%writefile {name}\n" + (HERE / name).read_text(encoding="utf-8")))

cells += [
    md("## A0: zero-shot (off-the-shelf ms-marco MiniLM-L6, 22.7M params)"),
    code("!python score.py --model zeroshot"),
    md("## A2: data-matched baselines (N = 50 / 200 train questions)\nThese are the fair baselines for the LLM weight-editing arm (exp03)."),
    code("!python train.py --n-train 50 --epochs 20 --tag n50 && python score.py --model n50"),
    code("!python train.py --n-train 200 --epochs 10 --tag n200 && python score.py --model n200"),
    md("## A1: full fine-tune (~90k questions, ~900k pairs, 1 epoch)\nResumes from the Drive checkpoint if the runtime disconnected."),
    code("!python train.py --n-train 0 --epochs 1 --tag full && python score.py --model full"),
    md("## Analysis"),
    code("!python analyze.py"),
    md("## Download the small result files (scores, summaries, train args; models stay on Drive)"),
    code("""
import shutil, glob, os
from google.colab import files
R = os.environ['RESULTS_DIR']
pack = '/content/exp02_results_small'
shutil.rmtree(pack, ignore_errors=True); os.makedirs(pack)
for f in glob.glob(f'{R}/*.json') + glob.glob(f'{R}/*.csv') + glob.glob(f'{R}/*/train_args.json'):
    dst = os.path.join(pack, os.path.relpath(f, R)); os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copy(f, dst)
files.download(shutil.make_archive('/content/exp02_results', 'zip', pack))
"""),
]

nb = {
    "cells": cells,
    "metadata": {"accelerator": "GPU", "colab": {"gpuType": "T4", "provenance": []},
                 "kernelspec": {"name": "python3", "display_name": "Python 3"}},
    "nbformat": 4,
    "nbformat_minor": 0,
}
(HERE / "exp02_colab.ipynb").write_text(json.dumps(nb, indent=1), encoding="utf-8")
print("wrote exp02_colab.ipynb with", len(cells), "cells")
